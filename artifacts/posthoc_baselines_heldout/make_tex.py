# ---------------- macros
def num(x, n):
    s = f"{x:.{n}f}"
    return s.replace("-", "$-$") if False else s


def m(x, n, sign=False):
    s = f"{x:+.{n}f}" if sign else f"{x:.{n}f}"
    return "\\ensuremath{" + s.replace("-", "-") + "}"


def ci(lo, hi, n, sign=True):
    f = (lambda v: f"{v:+.{n}f}") if sign else (lambda v: f"{v:.{n}f}")
    return "\\ensuremath{[" + f(lo) + "," + f(hi) + "]}"


def raw_contrast(r):
    """strongest edit minus matched control in the metric's own units (un-oriented)."""
    sgn = -1.0 if r["worse_direction"] == "increase" else 1.0
    lo, hi = r["contrast_ci995"]
    a, b = sgn * lo, sgn * hi
    return sgn * r["contrast_mean"], min(a, b), max(a, b)


macros = []
src = {}


def add(name, value, source):
    macros.append((name, value)); src[name] = source


for key, tag in (("C4_loop_collapse", "Loop"), ("C5_blandification", "Common")):
    r = cell[("lm_perplexity", key)]
    sm = r["song_mean_by_dose"]
    add(f"BlPpl{tag}After", m(sm["d3"], 2), f"lm_perplexity/{key}: song_mean_by_dose.d3")
    add(f"BlPpl{tag}Pct", m(abs(r["strongest_minus_unedited_pct"]), 0), f"lm_perplexity/{key}: |strongest_minus_unedited_pct| (drop, %)")
    d, lo, hi = raw_contrast(r)
    add(f"BlPpl{tag}Delta", m(d, 2, True), f"lm_perplexity/{key}: strongest minus matched control (raw units)")
    add(f"BlPpl{tag}DeltaCI", ci(lo, hi, 2), f"lm_perplexity/{key}: 99.5% CI of raw contrast")
    add(f"BlPpl{tag}Rho", m(r["dose_statistic_mean"], 3, True), f"lm_perplexity/{key}: oriented rank correlation (positive = toward better)")
    add(f"BlPpl{tag}RhoCI", ci(*r["dose_ci995"], 3), f"lm_perplexity/{key}: 99.5% CI of oriented rho")
add("BlPplUnedited", m(cell[("lm_perplexity", "C4_loop_collapse")]["song_mean_by_dose"]["official"], 2), "lm_perplexity: song_mean_by_dose.official")
