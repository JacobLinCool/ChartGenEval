add("BlPplCommonCrossMin", m(min(abs(c) for c in cross), 2), "verify/crosslm_c5_heldout.json: min |delta_ppl_song_mean| over 3 separately fitted scorers")
add("BlPplCommonCrossMax", m(max(abs(c) for c in cross), 2), "verify/crosslm_c5_heldout.json: max |delta_ppl_song_mean| over 3 separately fitted scorers")
add("BlPplCommonCrossWorstUpper", m(cross_hi, 2, True), "verify/crosslm_c5_heldout.json: largest 99.5% upper bound of delta over 3 scorers")
for key, tag in (("C4_loop_collapse", "Loop"), ("C5_blandification", "Common")):
    r = cell[("self_similarity", key)]
    sm = r["song_mean_by_dose"]
    add(f"BlSelfSim{tag}After", m(sm["d3"], 3), f"self_similarity/{key}: song_mean_by_dose.d3")
    add(f"BlSelfSim{tag}Pct", m(r["strongest_minus_unedited_pct"], 0), f"self_similarity/{key}: strongest_minus_unedited_pct (rise, %)")
add("BlSelfSimUnedited", m(cell[("self_similarity", "C4_loop_collapse")]["song_mean_by_dose"]["official"], 3), "self_similarity: song_mean_by_dose.official")
r = cell[("onset_f1_50ms", "C1_timing_jitter")]
assert r["replicate_level_exactly_invariant"] and r["song_mean_by_dose"]["d3"] == 1.0
add("BlFOneFiftyJitter", m(r["song_mean_by_dose"]["d3"], 3), "onset_f1_50ms/C1: song mean at +-30 ms (every replicate exactly 1)")
r = cell[("onset_f1_50ms", "C2_anchor_shift")]
assert r["song_mean_by_dose"]["d1"] == 1.0 and r["song_mean_by_dose"]["d2"] == 1.0
add("BlFOneFiftyShiftSixty", m(r["song_mean_by_dose"]["d3"], 3), "onset_f1_50ms/C2: song mean at 60 ms shift (exactly 1 at 15, 30 ms)")
r = cell[("onset_f1_20ms", "C1_timing_jitter")]
add("BlFOneTwentyJitter", m(r["song_mean_by_dose"]["d3"], 3), "onset_f1_20ms/C1: song mean at +-30 ms (exactly 1 at +-10, +-20 ms)")
